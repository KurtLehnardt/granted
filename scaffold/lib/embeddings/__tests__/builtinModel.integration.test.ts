/**
 * The real built-in model, end to end. Skipped unless the model files are in
 * scaffold/models/ (`npm run model:fetch`), so CI and fresh clones stay
 * hermetic. The Ollama comparison is also skipped unless an Ollama with
 * nomic-embed-text answers on 127.0.0.1:11434.
 *
 *   1. A known query embeds to (cosine similarity > 0.999 with) a pinned
 *      reference vector, so a model, dtype, tokenizer or pooling change
 *      can't slip in unnoticed. This used to assert an exact SHA-256 hash
 *      of the rounded vector, but an exact hash of floating-point ONNX
 *      output is architecture-dependent: the pinned hash was recorded on
 *      x86_64 and was confirmed not to reproduce on arm64/Apple Silicon,
 *      where the last bit or two of the floats differ. Cosine similarity
 *      above 0.999 still catches a genuinely changed model or changed
 *      weights (a different query's embedding scores well below that
 *      threshold against this same reference vector) while tolerating
 *      last-bit floating-point differences across CPUs.
 *   2. The shipped corpus vectors are what this model produces for those records.
 *   3. Ollama's nomic-embed-text gives the same vectors, which is why Local
 *      (Ollama) users can search the shipped corpus.
 */

